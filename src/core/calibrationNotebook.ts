/**
 * Rabi amplitude calibration notebook for a catalog operator. Follows the workflow of the qaas
 * example `pulse_level_custom_x_gate.ipynb`; the last cell writes a calibration result file that
 * the extension applies to the operator.
 */

import { estimate, formatSeconds } from "./estimate";
import { CALIBRATION_RESULT_SCHEMA } from "./operators";

export interface CalibrationNotebookInput {
  operator: string;
  /** Output of the bridge's pulseCode for this operator (classes + calibration + helpers). */
  operatorCode: string;
  project: string;
  resource: string;
  backend: string;
  qubit: string;
  resultDirectory: string;
}

/** Rounds of the Rabi calibration: (span relative to start amplitude, points, shots). */
export const RABI_ROUNDS: [number, number, number][] = [
  [0.6, 15, 500],
  [0.15, 11, 1000],
  [0.04, 11, 2000],
];
export const CHECK_SHOTS = 2000;
/** X and X·X with the custom and the native gate. */
export const CHECK_JOBS = 4;

/** Worst-case billed seconds, counting every sweep point as one VLQ job. */
export function calibrationCost(): number {
  const rounds = RABI_ROUNDS.reduce((a, [, points, shots]) => a + estimate({ shots, circuits: points }).high, 0);
  return rounds + estimate({ shots: CHECK_SHOTS, circuits: CHECK_JOBS }).high;
}

const py = (s: string) => JSON.stringify(s);

export function buildCalibrationNotebook(i: CalibrationNotebookInput): string {
  const cost = formatSeconds(calibrationCost());
  const jobs = RABI_ROUNDS.length + CHECK_JOBS;
  const cells: { cell_type: "markdown" | "code"; source: string }[] = [
    {
      cell_type: "markdown",
      source: `# Rabi amplitude calibration of \`${i.operator}\`

Calibrates the \`amplitude_i\` of the catalog operator \`${i.operator}\` (a custom \`prx\` implementation) on one qubit,
then checks X (expect P(1) ≈ 1) and X·X (expect P(1) ≈ 0) against the native gate.
The last cell writes a calibration result to \`.qaas/calibrations/\`; VS Code then offers to save it in the operator file
for the current calibration set.

Runs ${jobs} pulse-level jobs. Estimated billed time: up to ${cost} (every sweep point counted as one VLQ job).
Workflow from the qaas example \`pulse_level_custom_x_gate.ipynb\` (after Filippos Dakis, Experimental_results_IQM).
Needs \`qaas[iqm_qiskit]\`, \`matplotlib\`, QScheduler with pulse access, HEAppE 6.7.0+.`,
    },
    {
      cell_type: "code",
      source: `import json
from datetime import datetime
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
from exa.common.data.parameter import Sweep
from iqm.station_control.interface.models.jobs_new import JobStatus
from qiskit import QuantumCircuit

from qheappe_client import QProvider

LEXIS_PROJECT = ${py(i.project)}
RESOURCE = ${py(i.resource)} or None
BACKEND = ${py(i.backend)} or None
QUBIT = ${py(i.qubit)}
OPERATOR = ${py(i.operator)}
RESULT_DIR = Path(${py(i.resultDirectory)})
JOB_TIMEOUT = 900  # seconds per job`,
    },
    {
      cell_type: "markdown",
      source: "## Operator from the catalog\nGenerated by the QaaS extension from `.qaas/operators`.",
    },
    { cell_type: "code", source: i.operatorCode.trim() },
    { cell_type: "markdown", source: "## Connect and read the native gate" },
    {
      cell_type: "code",
      source: `provider = QProvider(LEXIS_PROJECT)
pulla = provider.get_pulla(RESOURCE, BACKEND)
compiler = pulla.get_qiskit_compiler()
register_qaas_operators(compiler)

settings = compiler.get_settings(circuits=[QuantumCircuit(1, 1)])
NATIVE_IMPL = settings.gate_definitions.prx.default_implementation.value
native_gate = settings.gates.prx[NATIVE_IMPL][QUBIT]
NATIVE_DURATION = float(native_gate.duration.value)
NATIVE_AMPLITUDE = float(native_gate.amplitude_i.value)
CALIBRATION_SET_ID = str(pulla.backend.architecture.calibration_set_id)

start = QAAS_OPERATOR_CALIBRATION.get(OPERATOR, {}).get(QUBIT, {})
DURATION = float(start.get("duration", NATIVE_DURATION))
Q_RATIO = float(start.get("amplitude_q", 0.0)) / float(start["amplitude_i"]) if start.get("amplitude_i") else 0.0
SHAPE_VALUES = {k: float(v) for k, v in start.items() if k not in ("duration", "amplitude_i", "amplitude_q")}
START_AMPLITUDE = float(start.get("amplitude_i", NATIVE_AMPLITUDE))
print(f"{pulla.quantum_computer_name} | calibration set {CALIBRATION_SET_ID} | qubit {QUBIT}")
print(f"native {NATIVE_IMPL}: duration {NATIVE_DURATION * 1e9:.1f} ns, amplitude_i {NATIVE_AMPLITUDE:.4f}")
print(f"{OPERATOR}: duration {DURATION * 1e9:.1f} ns, start amplitude_i {START_AMPLITUDE:.4f}, amplitude_q/amplitude_i {Q_RATIO:.3f}")`,
    },
    { cell_type: "markdown", source: "## Helpers" },
    {
      cell_type: "code",
      source: `def make_settings(circuits, *, shots, amplitude=None, custom=True):
    s = compiler.get_settings(circuits=circuits)
    if custom:
        s.gate_definitions.prx.default_implementation = OPERATOR
        s.gates.prx[OPERATOR][QUBIT].set_from_dict(
            {"duration": DURATION, "amplitude_i": amplitude, "amplitude_q": Q_RATIO * amplitude, **SHAPE_VALUES}
        )
    s.set_shots(shots)
    return s


def run(circuit, settings, sweeps=None):
    run_definition, context = compiler.compile(
        circuits=[circuit], components=[QUBIT], settings=settings, sweeps=sweeps or []
    )
    job = pulla.submit_playlist(run_definition, context=context)
    print(f"  HEAppE job {job.job_id.int}")
    status = job.wait_for_completion(timeout_secs=JOB_TIMEOUT, polling_interval=2)
    if status is not JobStatus.COMPLETED:
        raise RuntimeError(f"Job {job.job_id} ended {status}: {job.job_data.messages}")
    return job.result_exa(compiler=compiler)


def excited_probability(result):
    ds = result.dataset
    names = [n for n in ds.data_vars if n.startswith(f"{QUBIT}__") and n.endswith("excited_state_probability")]
    if not names:
        raise KeyError(f"No excited state probability for {QUBIT}: {list(ds.data_vars)}")
    return np.atleast_1d(np.asarray(ds[names[0]].values, dtype=float))


def peak_amplitude(amplitudes, probabilities):
    i = int(np.argmax(probabilities))
    if 0 < i < len(amplitudes) - 1:
        a, b, _ = np.polyfit(amplitudes[i - 1 : i + 2], probabilities[i - 1 : i + 2], 2)
        if a < 0:
            return float(np.clip(-b / (2 * a), amplitudes[i - 1], amplitudes[i + 1]))
    return float(amplitudes[i])


qc_x = QuantumCircuit(1, 1, name="x")
qc_x.x(0)
qc_x.measure(0, 0)
qc_xx = QuantumCircuit(1, 1, name="xx")
qc_xx.x(0)
qc_xx.barrier()
qc_xx.x(0)
qc_xx.measure(0, 0)`,
    },
    {
      cell_type: "markdown",
      source:
        "## Rabi rounds\nEach round sweeps the amplitude around the best value so far, narrower and with more shots.",
    },
    {
      cell_type: "code",
      source: `ROUNDS = ${JSON.stringify(RABI_ROUNDS)}  # (span relative to start, points, shots)
rounds, center = [], START_AMPLITUDE if 0 < START_AMPLITUDE < 1 else 0.3
for k, (span_factor, n_points, shots) in enumerate(ROUNDS, start=1):
    amplitudes = np.clip(np.linspace(center - span_factor * START_AMPLITUDE, center + span_factor * START_AMPLITUDE, n_points), 0.0, 1.0)
    s = make_settings([qc_x], shots=shots, amplitude=center)
    gate = s.gates.prx[OPERATOR][QUBIT]
    sweep = (Sweep(parameter=gate.amplitude_i.parameter, data=amplitudes), Sweep(parameter=gate.amplitude_q.parameter, data=Q_RATIO * amplitudes))
    print(f"Round {k}")
    probabilities = excited_probability(run(qc_x, s, sweeps=[sweep]))
    center = peak_amplitude(amplitudes, probabilities)
    print(f"  best amplitude {center:.5f}, max P(1) {probabilities.max():.3f}")
    rounds.append((amplitudes, probabilities, center))
AMPLITUDE = center

fig, axes = plt.subplots(1, len(rounds), figsize=(4 * len(rounds), 3.2))
for k, (ax, (a, p, best)) in enumerate(zip(np.atleast_1d(axes), rounds), start=1):
    ax.plot(a, p, "o-")
    ax.axvline(best, color="tab:red", linestyle="--", label=f"A = {best:.4f}")
    ax.set_title(f"Round {k}")
    ax.set_xlabel("amplitude_i")
    ax.set_ylabel("P(1) after X")
    ax.legend()
plt.tight_layout()
plt.show()`,
    },
    { cell_type: "markdown", source: "## Check against the native gate" },
    {
      cell_type: "code",
      source: `CHECK_SHOTS = ${CHECK_SHOTS}
checks = {}
for label, circuit in (("X", qc_x), ("X·X", qc_xx)):
    for name, custom in ((OPERATOR, True), (NATIVE_IMPL, False)):
        checks[f"{label} ({name})"] = float(excited_probability(run(circuit, make_settings([circuit], shots=CHECK_SHOTS, amplitude=AMPLITUDE, custom=custom)))[0])
for key, value in checks.items():
    print(f"{key:>28}: P(1) = {value:.4f}")`,
    },
    {
      cell_type: "markdown",
      source: "## Save the result\nVS Code offers to write it into the operator file for this calibration set.",
    },
    {
      cell_type: "code",
      source: `result = {
    "schema": ${py(CALIBRATION_RESULT_SCHEMA)},
    "operator": OPERATOR,
    "calibrationSetId": CALIBRATION_SET_ID,
    "backend": pulla.quantum_computer_name,
    "locus": QUBIT,
    "values": {"duration": DURATION, "amplitude_i": AMPLITUDE, "amplitude_q": Q_RATIO * AMPLITUDE, **SHAPE_VALUES},
    "native": {"implementation": NATIVE_IMPL, "duration": NATIVE_DURATION, "amplitude_i": NATIVE_AMPLITUDE},
    "checks": checks,
    "note": f"Rabi amplitude calibration ({len(ROUNDS)} rounds). " + ", ".join(f"{k} P(1)={v:.3f}" for k, v in checks.items()),
    "createdAt": datetime.now().astimezone().isoformat(timespec="seconds"),
}
RESULT_DIR.mkdir(parents=True, exist_ok=True)
path = RESULT_DIR / f"{OPERATOR}_{QUBIT}_{datetime.now():%Y%m%d_%H%M%S}.json"
path.write_text(json.dumps(result, indent=2))
print("Saved", path)`,
    },
  ];
  const nb = {
    cells: cells.map((c) =>
      c.cell_type === "code"
        ? { cell_type: "code", metadata: {}, execution_count: null, outputs: [], source: c.source }
        : { cell_type: "markdown", metadata: {}, source: c.source },
    ),
    metadata: {
      kernelspec: { name: "python3", display_name: "Python 3", language: "python" },
      language_info: { name: "python" },
    },
    nbformat: 4,
    nbformat_minor: 5,
  };
  return `${JSON.stringify(nb, null, 1)}\n`;
}
