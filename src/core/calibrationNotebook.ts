/**
 * Rabi amplitude calibration notebook for a catalog operator. Follows the workflow of the qaas
 * example `pulse_level_custom_x_gate.ipynb`; the last cell writes a calibration result file that
 * the extension applies to the operator.
 */

import type { LexisInstance } from "./devEnv";
import { estimate, formatSeconds } from "./estimate";
import { CALIBRATION_RESULT_SCHEMA } from "./operators";

export interface CalibrationNotebookInput {
  operator: string;
  /** Output of the bridge's pulseCode for this operator (classes + calibration + helpers). */
  operatorCode: string;
  project: string;
  resource: string;
  backend: string;
  qubit: string;
  resultDirectory: string;
  /** Non-production LEXIS instance (e.g. the test instance); undefined for production. */
  instance?: LexisInstance;
}

/** Rounds of the Rabi calibration: (span relative to start amplitude, points, shots). */
export const RABI_ROUNDS: [number, number, number][] = [
  [0.6, 15, 500],
  [0.15, 11, 1000],
  [0.04, 11, 2000],
];
export const CHECK_SHOTS = 2000;
/** X and X·X with the custom and the native gate. */
export const CHECK_JOBS = 4;

/** Worst-case billed seconds, counting every sweep point as one VLQ job. */
export function calibrationCost(): number {
  const rounds = RABI_ROUNDS.reduce((a, [, points, shots]) => a + estimate({ shots, circuits: points }).high, 0);
  return rounds + estimate({ shots: CHECK_SHOTS, circuits: CHECK_JOBS }).high;
}

const py = (s: string) => JSON.stringify(s);

/** LEXIS instance settings for the login cell; py4lexis reads the PY4LEXIS_* variables. */
function instanceLines(instance?: LexisInstance): string {
  const lines = [`LEXIS_API_URL = ${instance?.apiUrl ? py(instance.apiUrl) : "None"}  # None: production`];
  const vars: [string, string | undefined][] = [
    ["PY4LEXIS_AAI_URL", instance?.aaiUrl],
    ["PY4LEXIS_API_URL", instance?.apiUrl],
    ["PY4LEXIS_REALM", instance?.realm],
  ];
  for (const [name, value] of vars) {
    if (value) {
      lines.push(`os.environ[${py(name)}] = ${py(value)}`);
    }
  }
  return lines.join("\n");
}

